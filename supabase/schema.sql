alter table public.submission_media enable row level security;
alter table public.moderation_events enable row level security;
alter table public.submission_intake_events enable row level security;

-- Profiles contain roles, so only the owner/admin can read them. Public author names are snapshotted on submissions.
drop policy if exists "profiles readable" on public.profiles;
create policy "profiles readable" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
drop policy if exists "profile owner update" on public.profiles;
create policy "profile owner update" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid() and role = 'user');
drop policy if exists "admin profile update" on public.profiles;
create policy "admin profile update" on public.profiles for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- Submissions: public sees only published. Owners see their own. Admin sees all.
drop policy if exists "published or owner submissions readable" on public.submissions;
create policy "published or owner submissions readable" on public.submissions for select to anon, authenticated using (
  status = 'published' or author_id = auth.uid() or public.is_admin()
);
drop policy if exists "users insert own pending submissions" on public.submissions;
create policy "users insert own pending submissions" on public.submissions for insert to authenticated with check (
  author_id = auth.uid() and status = 'pending'
);
drop policy if exists "users delete own pending submissions" on public.submissions;
create policy "users delete own pending submissions" on public.submissions for delete to authenticated using (
  author_id = auth.uid() and status = 'pending'
);
-- Users do not update moderation fields. Admin changes happen through the Edge Function with service role.

-- Media metadata follows submission visibility.
drop policy if exists "media readable with submission" on public.submission_media;
create policy "media readable with submission" on public.submission_media for select to anon, authenticated using (
  exists (
    select 1 from public.submissions s
    where s.id = submission_id and (s.status = 'published' or s.author_id = auth.uid() or public.is_admin())
  )
);
drop policy if exists "users insert own media" on public.submission_media;
create policy "users insert own media" on public.submission_media for insert to authenticated with check (
  author_id = auth.uid()
  and storage_bucket = 'submission-inbox'
  and exists(select 1 from public.submissions s where s.id = submission_id and s.author_id = auth.uid() and s.status = 'pending')
);
drop policy if exists "users delete own pending media" on public.submission_media;
create policy "users delete own pending media" on public.submission_media for delete to authenticated using (
  author_id = auth.uid()
  and storage_bucket = 'submission-inbox'
  and exists(select 1 from public.submissions s where s.id = submission_id and s.author_id = auth.uid() and s.status = 'pending')
);

-- Intake events are intentionally not exposed through client RLS. The SECURITY DEFINER trigger writes them.

-- Audit events are admin-only.
drop policy if exists "admins read moderation events" on public.moderation_events;
create policy "admins read moderation events" on public.moderation_events for select to authenticated using (public.is_admin());

-- Storage buckets. Originals are never accepted: only WebP/WebM.
insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values ('submission-inbox', 'submission-inbox', false, 125829120, array['image/webp','video/webm'])
on conflict (id) do update set public=false, file_size_limit=excluded.file_size_limit, allowed_mime_types=excluded.allowed_mime_types;

insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values ('published-media', 'published-media', true, 125829120, array['image/webp','video/webm'])
on conflict (id) do update set public=true, file_size_limit=excluded.file_size_limit, allowed_mime_types=excluded.allowed_mime_types;

-- submission-inbox: users can upload/read/remove only their own top-level UID folder; admins can review all.
drop policy if exists "user upload own inbox media" on storage.objects;
create policy "user upload own inbox media" on storage.objects for insert to authenticated with check (
  bucket_id = 'submission-inbox' and (storage.foldername(name))[1] = auth.uid()::text
);
drop policy if exists "user read own or admin inbox media" on storage.objects;
create policy "user read own or admin inbox media" on storage.objects for select to authenticated using (
  bucket_id = 'submission-inbox' and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin())
);
drop policy if exists "user delete own inbox media" on storage.objects;
create policy "user delete own inbox media" on storage.objects for delete to authenticated using (
  bucket_id = 'submission-inbox' and (storage.foldername(name))[1] = auth.uid()::text
);
-- published-media is public-read because the bucket is public. Browser users cannot insert/update/delete it.

-- Grants for PostgREST. RLS still applies.
grant usage on schema public to anon, authenticated, service_role;
grant select on public.profiles to authenticated;
grant select on public.submissions, public.submission_media to anon, authenticated;
grant insert, delete on public.submissions, public.submission_media to authenticated;
grant select on public.moderation_events to authenticated;

-- Secret-key/admin clients bypass RLS but still need SQL privileges.
grant all on public.profiles, public.submissions, public.submission_media, public.moderation_events, public.submission_intake_events to service_role;
grant usage, select on all sequences in schema public to service_role;

