-- LLM Bible Community schema
-- Run once in Supabase SQL Editor. Safe to re-run for upgrades.
-- Auth passwords are managed by Supabase Auth (auth.users). Never store plaintext passwords here.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 2 and 40),
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references public.profiles(id) on delete cascade,
  author_display_name text not null default '회원' check (char_length(author_display_name) between 1 and 40),
  slug text not null unique,
  title text not null check (char_length(title) between 5 and 100),
  category text not null check (char_length(category) between 1 and 40),
  summary text not null check (char_length(summary) between 20 and 500),
  prompt_text text not null check (char_length(prompt_text) between 30 and 30000),
  result_text text not null check (char_length(result_text) between 30 and 30000),
  model_name text not null check (char_length(model_name) between 1 and 80),
  model_version text check (model_version is null or char_length(model_version) <= 120),
  source_notes text check (source_notes is null or char_length(source_notes) <= 5000),
  status text not null default 'pending' check (status in ('pending','published','archived','rejected')),
  moderation_note text,
  review_scores jsonb,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.submission_media (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.submissions(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('image','video')),
  storage_bucket text not null check (storage_bucket in ('submission-inbox','published-media')),
  storage_path text not null,
  mime_type text not null check (mime_type in ('image/webp','video/webm')),
  bytes bigint not null check (bytes >= 0 and bytes <= 125829120),
  width integer check (width is null or width > 0),
  height integer check (height is null or height > 0),
  duration_seconds numeric check (duration_seconds is null or (duration_seconds >= 0 and duration_seconds <= 90.5)),
  alt_text text check (alt_text is null or char_length(alt_text) <= 300),
  sort_order integer not null default 0 check (sort_order between 0 and 20),
  created_at timestamptz not null default now(),
  unique(storage_bucket, storage_path)
);

create table if not exists public.moderation_events (
  id bigint generated by default as identity primary key,
  submission_id uuid not null references public.submissions(id) on delete cascade,
  moderator_id uuid references public.profiles(id) on delete set null,
  action text not null check (action in ('publish','archive','reject','restore','note')),
  note text,
  scores jsonb,
  created_at timestamptz not null default now()
);

-- Durable intake events make the hourly submission limit resistant to create/delete loops.
create table if not exists public.submission_intake_events (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists submissions_status_published_idx on public.submissions(status, published_at desc);
create index if not exists submissions_author_idx on public.submissions(author_id, created_at desc);
create index if not exists submission_media_submission_idx on public.submission_media(submission_id, sort_order);
create index if not exists moderation_events_submission_idx on public.moderation_events(submission_id, created_at desc);
create index if not exists submission_intake_events_author_idx on public.submission_intake_events(author_id, created_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at before update on public.profiles for each row execute function public.touch_updated_at();
drop trigger if exists submissions_touch_updated_at on public.submissions;
create trigger submissions_touch_updated_at before update on public.submissions for each row execute function public.touch_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles(id, display_name, role)
  values (
    new.id,
    case
      when char_length(trim(coalesce(new.raw_user_meta_data ->> 'display_name', ''))) >= 2
        then left(trim(new.raw_user_meta_data ->> 'display_name'), 40)
      when char_length(split_part(coalesce(new.email, ''), '@', 1)) >= 2
        then left(split_part(new.email, '@', 1), 40)
      else '회원'
    end,
    'user'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- Basic anti-spam guard for direct inserts: max 5 new submissions per hour per account.
create or replace function public.guard_submission_rate()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  recent_count integer;
  v_display_name text;
begin
  if auth.uid() is null or new.author_id <> auth.uid() then
    raise exception '작성자 인증이 올바르지 않습니다.';
  end if;
  select display_name into v_display_name from public.profiles where id = auth.uid();
  if v_display_name is null then raise exception '프로필을 찾을 수 없습니다.'; end if;
  new.author_display_name := v_display_name;
  select count(*) into recent_count
  from public.submission_intake_events
  where author_id = auth.uid() and created_at > now() - interval '1 hour';
  if recent_count >= 5 then
    raise exception '한 시간에 최대 5건까지 제출할 수 있습니다.';
  end if;
  insert into public.submission_intake_events(author_id) values (auth.uid());
  return new;
end;
$$;

drop trigger if exists submissions_rate_guard on public.submissions;
create trigger submissions_rate_guard before insert on public.submissions for each row execute function public.guard_submission_rate();

alter table public.profiles enable row level security;
